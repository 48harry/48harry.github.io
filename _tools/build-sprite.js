const symbols = Object.entries(ICONS).map(([id, [style, name]]) => {
  const src = fs.readFileSync(path.join(SVGS, style, name + '.svg'), 'utf8');
  const viewBox = src.match(/viewBox="([^"]+)"/)[1];
  const inner = src
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
  return `<symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>`;
});

